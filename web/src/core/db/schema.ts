import { column, Schema, Table } from '@powersync/web'

// Schéma PowerSync : une table par table Postgres (supabase/migrations/0001_schema.sql).
// La colonne `id` (text) est implicite. Correspondance des types :
// uuid / text / timestamptz -> text, integer / boolean -> integer, double precision -> real.
const t = column.text
const i = column.integer
const r = column.real

// Colonnes de synchro communes à toutes les tables
const sync = { user_id: t, updated_at: t, deleted_at: t }

export const AppSchema = new Schema({
  exercises: new Table({
    ...sync,
    name: t,
    category: t,
    muscle_groups: t,
    description: t,
    is_favorite: i,
    is_custom: i,
    image_url: t,
    exercise_type: t,
    equipment: t,
    muscle_primary: t,
    is_bodyweight: i,
  }),
  seances: new Table({
    ...sync,
    nom: t,
    groupes_musculaires: t,
    duree_estimee_min: i,
    notes: t,
    seance_category: t,
    created_at: t,
    is_archived: i,
  }),
  blocs_seance: new Table({
    ...sync,
    seance_id: t,
    nom: t,
    type: t,
    position: i,
    duree_min: i,
    description: t,
    temps_repos_inter_sec: i,
    temps_repos_fin_round_sec: i,
    instance_seance_id: t,
    bloc_source_id: t,
  }),
  exercices_seance: new Table({
    ...sync,
    seance_id: t,
    exercise_id: t,
    bloc_id: t,
    superset_groupe: t,
    position: i,
    nombre_series_prevues: i,
    reps_cibles: t,
    charge_cible: t,
    tempo: t,
    reps_type: t,
    temps_repos_sec: i,
    consigne_cle: t,
    equipement: t,
    avertissement: t,
    instance_seance_id: t,
    exercice_source_id: t,
    is_bilateral: i,
    progression_activee: i,
    systeme_progression: t,
    reps_min: i,
    reps_max: i,
    increment_kg: r,
    increment_duree_sec: i,
    seuil_deload: i,
    type_exercice: t,
    increment_pct: r,
    is_bodyweight: i,
  }),
  instances_seance: new Table({
    ...sync,
    seance_id: t,
    date: t,
    notes: t,
    is_completed: i,
    completed_at: t,
    duration_seconds: i,
    created_at: t,
  }),
  series_realisees: new Table({
    ...sync,
    instance_seance_id: t,
    exercice_seance_id: t,
    numero_serie: i,
    reps_realisees: i,
    charge_kg: r,
    charge_label: t,
    rpe: r,
    notes: t,
    is_completed: i,
  }),
  objectifs_progression: new Table({
    ...sync,
    seance_id: t,
    exercise_id: t,
    charge_cible: r,
    reps_cible: i,
    duree_cible_sec: i,
    compteur_echec: i,
    derniere_maj: t,
    nombre_series_cible: i,
  }),
  user_settings: new Table({
    ...sync,
    equipment_json: t,
    panda_variant: t,
    dark_mode: i,
  }),
})
